# idade é a variável que armazena a idade da pessoa, nesse caso 20 anos
idade = 20

# if é a estrutura de controle de fluxo que avalia a condição idade >= 18
if idade >= 18:

# se for verdadeira, o código dentro do bloco if será executado, 
# nesse cao se tiver 18 anos ou mais, a pessoa pode entrar   
    print("Pode entrar!")      # executa se a condição for verdadeira
    
# else (senão) é a parte do código que será executada se a condição for falsa, 
# ou seja, se a pessoa tiver menos de 18 anos 
else:

# print é a função que exibe a mensagem "Não pode entrar." na tela, indicando que a 
# pessoa não tem idade suficiente para entrar    
    print("Não pode entrar.")   # executa se a condição for falsa