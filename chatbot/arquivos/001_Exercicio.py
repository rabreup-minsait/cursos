# Exercício 1: Variáveis e Tipos de Dados
# nome é a variável que armazena o nome da pessoa  
# o sinal de = é usado para atribuir um valor à variável, como é uma string, 
# o valor é colocado entre aspas então Maria é o valor atribuído à variável nome
nome = "Maria"

# idade é a variável que armazena a idade da pessoa 
# como é um número inteiro, o valor é escrito sem aspas
idade = 30

# altura é a variável que armazena a altura da pessoa
# como é um número decimal, o valor é escrito com ponto e sem aspas
altura = 1.65

# ativo é a variável que indica se a pessoa está ativa ou não
# como é um valor booleano, o valor é escrito como True ou False
ativo = True

# agora vamos imprimir os valores das variáveis para verificar se estão corretos
# print é a função usada para exibir informações na tela os parênteses são usados para passar o valor 
# que queremos imprimir, colocaremos o nome da variável dentro dos parênteses
print(nome)
print(idade)
print(altura)
print(ativo)

