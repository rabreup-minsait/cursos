                <div class="gloss-item">
                    <strong>Prazo</strong>
                    <p>Tempo definido para concluir atividades ou entregas.</p>
                </div>
                <div class="gloss-item">
                    <strong>Risco</strong>
                    <p>Algo que pode acontecer e afetar o projeto.</p>
