        <section class="lesson-talk">
            <div class="teacher-text">
                <p>
                    Se alguém aparece com uma ideia incrível, mas ninguém sabe exatamente o que fazer,
                    quem participa, quando precisa ficar pronto e qual resultado deve ser entregue,
                    a chance de confusão é enorme. Gestão de projetos existe justamente para transformar
                    essa ideia em um caminho mais claro.
                </p>

                <p>
                    Isso não significa encher o projeto de burocracia. Significa dar direção ao trabalho.
                    Uma equipe pode ter vontade, criatividade e energia, mas, sem combinados mínimos,
                    começa a depender demais do improviso. E improviso até ajuda em alguns momentos,
                    mas não pode ser o método principal.
                </p>
            </div>

            <div class="student-question">
                <div class="student-raise-hand" aria-hidden="true">
