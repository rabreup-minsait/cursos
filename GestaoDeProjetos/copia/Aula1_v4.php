                </div>
                <div class="student-question-box">
                    Então gestão de projetos é só organização?
                </div>
            </div>

            <div class="teacher-text">
                <p>
                    Organização faz parte, mas não é só isso. Gestão de projetos é organização com direção.
                    Você não organiza por organizar. Você organiza para chegar a um resultado, gerar valor,
                    reduzir confusão e ajudar as pessoas a trabalharem melhor juntas.
                </p>

                <p>
                    Uma lista de tarefas pode ajudar. Um cronograma pode ajudar. Um quadro visual também.
                    Mas essas ferramentas só fazem sentido quando existe clareza sobre o objetivo,
                    o contexto, as pessoas envolvidas, as entregas esperadas e os riscos do caminho.
                </p>
            </div>

            <div class="student-question">
                <div class="student-raise-hand" aria-hidden="true">
                    <span class="student-head"></span>
                    <span class="student-body"></span>
                    <span class="student-arm"></span>
                </div>
                <div class="student-question-box">
                    Mas se eu arrumar meu quarto hoje, isso é um projeto?
                </div>
            </div>

            <div class="teacher-text">
                <p>
                    Depende. Se for apenas uma tarefa comum do dia, como guardar algumas roupas ou organizar a mesa,
                    provavelmente é rotina. Agora, se a ideia é transformar o quarto inteiro, mudar a disposição dos móveis,
                    criar um espaço de estudo, separar materiais, definir etapas e chegar a um resultado diferente,
                    aí já começa a parecer um projeto.
                </p>

                <p>
                    A diferença está na mudança que se quer provocar. Rotina mantém o dia funcionando.
                    Projeto cria, transforma, melhora ou entrega algo em um contexto específico.
                </p>
            </div>

            <div class="student-question">
                <div class="student-raise-hand" aria-hidden="true">
                    <span class="student-head"></span>
                    <span class="student-body"></span>
                    <span class="student-arm"></span>
                </div>
                <div class="student-question-box">
                    E onde entra o Scrum nisso?
                </div>
            </div>

            <div class="teacher-text">
                <p>
                    O Scrum entra como uma forma prática de organizar o trabalho em ciclos curtos.
                    Em vez de tentar resolver tudo de uma vez, a equipe trabalha por partes,
                    acompanha o que está acontecendo, revisa o que foi feito e ajusta o caminho quando necessário.
                </p>

                <p>
                    Essa lógica combina muito bem com projetos em que nem tudo está claro desde o início.
                    Às vezes a equipe entende melhor o problema enquanto trabalha. O Scrum ajuda a manter
                    o foco, dar visibilidade ao andamento e melhorar a cada ciclo.
                </p>
            </div>
        </section>

