            <div class="glossary-inline">
                <div class="gloss-item">
                    <strong>Projeto</strong>
                    <p>Esforço temporário para criar uma entrega específica.</p>
                </div>
                <div class="gloss-item">
                    <strong>Stakeholder</strong>
                    <p>Pessoa ou grupo que influencia ou é impactado pelo projeto.</p>
                </div>
                <div class="gloss-item">
                    <strong>Entrega</strong>
                    <p>Resultado concreto do projeto. Em inglês, deliverable.</p>
                </div>
                <div class="gloss-item">
                    <strong>Prazo</strong>
                    <p>Tempo definido para concluir atividades ou entregas.</p>
                </div>
                <div class="gloss-item">
                    <strong>Risco</strong>
                    <p>Algo que pode acontecer e afetar o projeto.</p>
                </div>
                <div class="gloss-item">
                    <strong>Scrum</strong>
                    <p>Framework ágil que organiza o trabalho em ciclos curtos.</p>
                </div>
            </div>
