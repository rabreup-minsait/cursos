            <div class="speech student">
                <strong>Aluno:</strong>
                “Mas se eu arrumar meu quarto hoje, isso é um projeto?”
            </div>

            <div class="speech teacher">
                <strong>Professor:</strong>
                “Depende. Se for apenas uma tarefa comum do dia, é mais uma rotina. Agora, se você
                decidiu transformar o quarto inteiro, planejar espaço, definir etapas, separar materiais,
                reorganizar tudo e entregar um resultado final diferente, aí já começa a parecer um projeto.”
            </div>

            <div class="speech student">
                <strong>Aluno:</strong>
                “E onde entra o Scrum nisso?”
            </div>

            <div class="speech teacher">
                <strong>Professor:</strong>
                “Ótima pergunta. O Scrum entra como uma forma prática de trabalhar projetos em partes menores,
                com ciclos curtos, acompanhamento frequente e melhoria contínua. Em vez de tentar resolver tudo
                de uma vez, a gente organiza o trabalho em blocos mais enxutos.”
