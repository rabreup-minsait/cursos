  <p>Essa distinção parece simples, mas muda a forma de organizar o trabalho. Se nós tratamos uma rotina como projeto, criamos controle desnecessário. Se tratamos um projeto como rotina, deixamos de planejar, de prever riscos, de combinar papéis e de acompanhar entregas. Cada tipo de trabalho pede uma forma de gestão diferente.</p>

  <div class="sbreak">os elementos básicos de um projeto</div>

  <p>Para um projeto começar a ficar claro, nós precisamos enxergar alguns elementos básicos. Não precisa decorar como se fosse fórmula, mas precisa reconhecer quando eles aparecem. Sem esses elementos, o projeto fica solto demais.</p>

  <div class="flow">
    <div class="fbox hi"><span class="fe">🎯</span><span class="fl">objetivo</span><span class="fn2">direção</span></div>
    <div class="farrow">→</div>
    <div class="fbox hi"><span class="fe">📦</span><span class="fl">entregas</span><span class="fn2">resultado</span></div>
    <div class="farrow">→</div>
    <div class="fbox hi"><span class="fe">👥</span><span class="fl">pessoas</span><span class="fn2">envolvidos</span></div>
    <div class="farrow">→</div>
    <div class="fbox hi"><span class="fe">⏱️</span><span class="fl">prazo</span><span class="fn2">tempo</span></div>
  </div>

  <p>O <strong>objetivo</strong> é a direção do projeto. Ele responde ao que nós queremos alcançar. Um objetivo fraco é vago demais: “fazer uma feira legal”. Um objetivo melhor já mostra intenção e resultado: “organizar uma feira cultural para apresentar talentos dos alunos e envolver a comunidade escolar em uma manhã de atividades”.</p>

  <p>A <strong>entrega</strong> é aquilo que será produzido ou disponibilizado. Em inglês, é comum aparecer a palavra <em>deliverable</em>. Em um projeto, entrega precisa ser algo que conseguimos reconhecer. No exemplo da feira, as entregas podem ser: programação definida, espaço organizado, lista de apresentações, divulgação feita, barracas montadas, regras de participação e avaliação final.</p>

  <p>As <strong>pessoas envolvidas</strong> incluem quem faz, quem decide, quem apoia, quem usa, quem é impactado e quem pode interferir no projeto. Em gestão de projetos, usamos muito a palavra <em>stakeholder</em> para falar de partes interessadas. Um stakeholder pode ser um aluno, professor, coordenação, família, visitante, patrocinador, fornecedor ou qualquer pessoa/grupo que afete ou seja afetado pelo projeto.</p>

  <p>O <strong>prazo</strong> mostra quando as coisas precisam acontecer. Prazo não é só a data final. Ele também inclui marcos intermediários: quando definir a programação, quando divulgar, quando confirmar materiais, quando testar som, quando revisar o espaço, quando encerrar inscrições. Sem prazos intermediários, o projeto fica com uma data final bonita e um caminho invisível.</p>

  <p>Os <strong>recursos</strong> são tudo que o projeto precisa para acontecer: pessoas, tempo, dinheiro, espaço, equipamentos, materiais, ferramentas, autorizações e informação. Um erro comum é pensar em recurso apenas como dinheiro. Às vezes o maior recurso do projeto é disponibilidade das pessoas. Às vezes é uma sala. Às vezes é acesso a um computador. Às vezes é autorização da direção.</p>

  <p>Os <strong>riscos</strong> são incertezas que podem afetar o projeto. Risco não é só problema que já aconteceu. Se já aconteceu, virou problema ou questão em aberto. Risco é algo que pode acontecer. Pode chover no dia do evento. O fornecedor pode atrasar. A sala pode não estar disponível. Poucos alunos podem se inscrever. O material pode não chegar. Identificar risco não é pessimismo; é maturidade.</p>

  <div class="dica">
    <strong>Regra simples:</strong> se nós conseguimos dizer objetivo, entregas, pessoas envolvidas, prazo, recursos e riscos principais, o projeto já começa a sair da névoa.
  </div>

  <p>Existe ainda um conceito que aparece muito cedo em qualquer projeto: <strong>escopo</strong>. Escopo é o que está dentro e o que está fora do projeto. Ele evita que o projeto cresça sem controle. Se a feira cultural inclui apresentações, exposição de trabalhos e arrecadação de alimentos, mas não inclui show externo, praça de alimentação paga ou aluguel de palco, isso precisa ficar claro. O escopo protege o projeto de virar outra coisa no meio do caminho.</p>

  <p>Quando o escopo não está claro, cada pessoa imagina um projeto diferente. Uma pessoa acha que a feira será pequena, outra imagina um evento enorme. Uma pessoa pensa em duas horas, outra pensa em um dia inteiro. Uma pessoa acha que haverá comida, outra acha que não. O problema não é sonhar grande; o problema é não combinar o tamanho do sonho.</p>

  <div class="bubble">
    <div class="bubble-avatar">🙋</div>
    <div class="bubble-body">E se no meio do caminho alguém pedir mais coisas?</div>
  </div>

  <p>Isso acontece bastante. Projetos mudam, e algumas mudanças fazem sentido. Mas mudança precisa ser analisada. Se alguém pede para incluir uma apresentação extra, precisamos perguntar: cabe no tempo? muda custo? exige novo material? afeta a equipe? melhora o valor do projeto? Se sim, talvez entre. Se não, talvez fique para outro momento. Gerenciar projeto não é dizer “não” para tudo; é entender consequência antes de aceitar.</p>

  <div class="sbreak">do objetivo às tarefas</div>

  <p>Depois de entender o objetivo e o escopo, precisamos transformar o projeto em partes menores. É aqui que muita gente se perde, porque olha para o projeto inteiro e acha grande demais. “Organizar uma feira cultural” parece enorme. Mas quando quebramos em blocos, fica mais administrável.</p>

  <p>Podemos começar pelas entregas maiores: programação, divulgação, espaço, materiais, apresentações, equipe de apoio e encerramento. Depois quebramos cada entrega em tarefas. Divulgação, por exemplo, pode incluir criar cartaz, escrever texto, publicar nos grupos, pedir autorização para colocar aviso no mural e lembrar os professores.</p>

