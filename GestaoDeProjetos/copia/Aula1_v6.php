  <p>Um <strong>impedimento</strong> é algo que bloqueia o avanço de uma tarefa. Se a equipe precisa de autorização da direção para usar o pátio e essa autorização ainda não saiu, existe um impedimento. Se a tarefa depende de uma informação que ninguém confirmou, existe um impedimento. Se o material não chegou, existe um impedimento.</p>

  <p>Também é importante diferenciar <strong>risco</strong> de <strong>problema</strong>. Risco é algo que pode acontecer. Problema é algo que já aconteceu. “Pode chover no dia do evento” é risco. “Choveu e o pátio ficou alagado” é problema. Essa diferença ajuda a equipe a agir melhor: risco se planeja; problema se trata.</p>

  <div class="atencao">
    <strong>Atenção:</strong> acompanhar projeto não é esperar o prazo final para descobrir que deu errado. Acompanhamento bom aparece antes do susto.
  </div>

  <p>Um projeto pequeno pode ser acompanhado com um quadro simples de três colunas: a fazer, em andamento e concluído. Isso já cria visibilidade. Quando a equipe olha para o quadro, entende rapidamente o que existe, o que está andando e o que já terminou.</p>

