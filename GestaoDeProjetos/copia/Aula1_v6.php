  <p>Essa quebra é parecida com uma técnica muito usada chamada <strong>EAP</strong>, Estrutura Analítica do Projeto. A EAP ajuda a decompor o projeto em partes menores e mais controláveis. Não precisamos complicar agora. A ideia principal é simples: projeto grande demais precisa ser quebrado em entregas e tarefas menores.</p>

  <p>A partir dessas tarefas, começamos a montar o <strong>cronograma</strong>. Cronograma é a organização das atividades no tempo. Ele mostra o que precisa acontecer antes, durante e depois. Um cronograma simples já ajuda muito, porque revela dependências. Algumas tarefas só podem começar depois de outras.</p>

  <p>Por exemplo, não dá para divulgar uma programação antes de definir quais apresentações vão acontecer. Não dá para reservar uma sala sem saber a data. Não dá para montar o espaço sem saber a quantidade de barracas ou mesas. Quando percebemos essas dependências, o cronograma deixa de ser uma lista de datas e passa a ser um mapa de sequência.</p>

