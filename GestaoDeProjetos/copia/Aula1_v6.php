  <p>Percebe como o cronograma não é só calendário? Ele mostra ordem, responsabilidade e dependência. Para projetos pequenos, uma tabela simples pode funcionar. Para projetos maiores, podemos usar uma planilha, um quadro Kanban, um gráfico de Gantt ou uma ferramenta específica. A ferramenta muda, mas a lógica continua sendo organizar o trabalho no tempo.</p>

  <div class="sbreak">execução e acompanhamento</div>

  <p>Planejar é importante, mas projeto não vive só de planejamento. Em algum momento, a equipe começa a executar. Executar é colocar as tarefas em movimento: produzir materiais, falar com pessoas, confirmar recursos, criar documentos, testar soluções, montar espaços, revisar entregas e resolver imprevistos.</p>

  <p>Durante a execução, o papel da gestão não é vigiar pessoas o tempo inteiro. É acompanhar se o projeto continua indo na direção certa. O acompanhamento serve para responder perguntas simples: o que já foi feito? o que está em andamento? o que atrasou? o que bloqueou? o que mudou? o que precisa de decisão?</p>

