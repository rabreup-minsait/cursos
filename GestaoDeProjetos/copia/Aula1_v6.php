    <div class="farrow">→</div>
    <div class="fbox hi"><span class="fe">⚙️</span><span class="fl">em andamento</span><span class="fn2">tarefas sendo feitas</span></div>
    <div class="farrow">→</div>
    <div class="fbox"><span class="fe">✅</span><span class="fl">concluído</span><span class="fn2">tarefas finalizadas</span></div>
  </div>

  <p>Esse tipo de quadro é simples, mas poderoso. Ele evita que tudo fique na cabeça das pessoas. Também ajuda a perceber excesso de tarefas em andamento. Quando muita coisa começa e pouca coisa termina, o projeto parece movimentado, mas não necessariamente avança.</p>

  <div class="break">
    <span class="be">☕</span>
    <h3>Pausa rápida para café</h3>
    <p>Na volta, nós pegamos uma ideia comum e montamos a primeira versão de um projeto completo, ainda simples, mas já com estrutura.</p>
  </div>

  <div class="sbreak">montando a primeira ficha de projeto</div>

  <p>Vamos usar um exemplo único para organizar tudo: uma feira cultural na escola. A ideia inicial é simples demais: “fazer uma feira”. Para virar projeto, nós precisamos completar essa ideia com informações mínimas.</p>

  <p>Primeiro, precisamos entender o <strong>problema ou oportunidade</strong>. Talvez os alunos tenham poucos espaços para apresentar talentos. Talvez a escola queira aproximar as famílias. Talvez exista uma campanha de arrecadação. Talvez a turma queira criar uma experiência diferente antes do fim do semestre. O motivo muda a forma de organizar o projeto.</p>

  <p>Depois, precisamos declarar o <strong>valor esperado</strong>. No nosso exemplo, o valor pode ser: criar um espaço de participação dos alunos, fortalecer a comunidade escolar e desenvolver organização, comunicação e colaboração entre os envolvidos.</p>

  <p>Com isso, conseguimos formar um <strong>objetivo</strong> mais claro: organizar uma feira cultural escolar, em uma manhã, com apresentações e exposições feitas pelos alunos, envolvendo professores, famílias e comunidade escolar.</p>

  <p>Repara que esse objetivo ainda é simples, mas já dá muito mais direção do que “fazer uma feira”. Ele mostra o tipo de evento, o público, a duração aproximada e a intenção.</p>

  <div class="exercise">
    <span class="ex-tag">primeira prática</span>
    <h3>Transformando uma ideia em projeto</h3>
    <p>Escolha uma ideia simples e responda sem tentar deixar perfeito. O objetivo é tirar a ideia da cabeça e colocar no papel.</p>
    <ol>
      <li>Qual é a ideia?</li>
      <li>Que problema, necessidade ou oportunidade ela resolve?</li>
      <li>Que valor ela pode gerar?</li>
      <li>Para quem esse valor importa?</li>
      <li>Qual seria uma primeira entrega visível?</li>
    </ol>
  </div>

  <p>Depois disso, começamos a pensar nas <strong>entregas</strong>. No exemplo da feira, não basta dizer “evento realizado”. Essa é a entrega final. Antes dela, existem entregas intermediárias: tema definido, lista de apresentações, espaço reservado, divulgação pronta, materiais organizados, escala da equipe, programação publicada, estrutura montada e avaliação final.</p>

  <p>Quando quebramos o projeto em entregas, ele deixa de parecer uma massa confusa. Cada entrega vira um pedaço do projeto. Depois cada pedaço vira tarefa.</p>

