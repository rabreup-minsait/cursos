  <p>Agora entramos nos <strong>papéis</strong>. Papel não é cargo bonito. Papel é responsabilidade. Em projeto pequeno, uma pessoa pode acumular mais de um papel. Alguém coordena, alguém cuida da comunicação, alguém organiza materiais, alguém acompanha prazos, alguém fala com professores, alguém confere se as entregas ficaram prontas.</p>

  <p>Quando ninguém tem papel definido, duas coisas costumam acontecer: ou ninguém faz, porque acha que outra pessoa faria, ou várias pessoas fazem a mesma coisa sem combinar. Nos dois casos, o projeto perde energia.</p>

  <div class="dica">
    <strong>Uma pergunta simples ajuda muito:</strong> se essa tarefa atrasar, quem percebe primeiro? Se ninguém souber responder, provavelmente a responsabilidade não está clara.
  </div>

  <p>Depois dos papéis, vem o <strong>cronograma inicial</strong>. Ele não precisa ser perfeito. Precisa ser útil. Em um primeiro momento, podemos organizar por semanas ou por datas principais. O cronograma deve mostrar o encadeamento das tarefas e permitir acompanhamento.</p>

  <p>Também precisamos cuidar das <strong>premissas</strong> e <strong>restrições</strong>. Premissa é algo que consideramos verdadeiro para planejar, mesmo sem garantia total. Por exemplo: “a escola permitirá o uso do pátio”. Restrição é um limite imposto ao projeto. Por exemplo: “o evento precisa acontecer até 11h30” ou “não haverá orçamento para contratar fornecedores”.</p>

  <p>Essas duas palavras aparecem bastante em gestão de projetos porque ajudam a evitar planejamento fantasioso. Se existe uma restrição de tempo, dinheiro ou espaço, o projeto precisa respeitar isso. Se existe uma premissa importante, precisamos acompanhar se ela continua válida.</p>

  <div class="lousa">
    <div class="lousa-title">ficha inicial do projeto</div>
    <div class="lousa-row"><span class="bul">1</span><span><strong>Ideia:</strong> o que queremos fazer?</span></div>
    <div class="lousa-row"><span class="bul">2</span><span><strong>Valor:</strong> por que isso importa?</span></div>
    <div class="lousa-row"><span class="bul">3</span><span><strong>Objetivo:</strong> que resultado queremos alcançar?</span></div>
    <div class="lousa-row"><span class="bul">4</span><span><strong>Entregas:</strong> o que precisa existir no final?</span></div>
    <div class="lousa-row"><span class="bul">5</span><span><strong>Pessoas:</strong> quem participa ou é impactado?</span></div>
    <div class="lousa-row"><span class="bul">6</span><span><strong>Prazo:</strong> quando precisa acontecer?</span></div>
    <div class="lousa-row"><span class="bul">7</span><span><strong>Riscos:</strong> o que pode atrapalhar?</span></div>
  </div>

  <p>Quando essa ficha existe, o projeto ainda não está totalmente planejado, mas já tem base. A partir dela, podemos construir escopo, cronograma, responsabilidades, acompanhamento e comunicação. Sem ela, qualquer planejamento fica frágil, porque ninguém sabe exatamente qual projeto está tentando conduzir.</p>

  <p>Essa ficha também ajuda a conversar. Um projeto começa a melhorar quando as pessoas olham para a mesma informação. Se tudo está apenas na cabeça de cada um, cada pessoa trabalha com uma versão diferente do projeto.</p>

  <div class="exercise">
    <span class="ex-tag">atividade aplicada</span>
    <h3>Primeira ficha do seu projeto</h3>
    <p>Preencha a primeira versão da ficha usando uma ideia real. Pode ser algo pequeno. O importante é que exista valor para alguém.</p>
    <ol>
      <li><strong>Nome do projeto:</strong> dê um nome simples.</li>
      <li><strong>Ideia inicial:</strong> descreva em uma frase.</li>
      <li><strong>Valor esperado:</strong> explique por que esse projeto importa.</li>
      <li><strong>Objetivo:</strong> escreva o resultado que queremos alcançar.</li>
      <li><strong>Entregas principais:</strong> liste de três a cinco entregas.</li>
      <li><strong>Pessoas envolvidas:</strong> liste quem participa, decide, apoia ou é impactado.</li>
      <li><strong>Prazo inicial:</strong> defina uma data ou período.</li>
      <li><strong>Riscos principais:</strong> liste pelo menos três coisas que podem atrapalhar.</li>
    </ol>
  </div>

  <p>Com essa primeira ficha, nós já conseguimos sair do campo da intenção. O projeto ainda vai precisar de refinamento, mas já existe uma base para conversar, ajustar e planejar melhor.</p>

  <p>Na próxima etapa, nós pegamos essa ficha e trabalhamos com mais precisão em objetivo, escopo e entregas. É aí que a ideia começa a ficar preparada para virar um plano de projeto de verdade.</p>

